[CmdletBinding()]
param(
    [Parameter(Mandatory = $true)]
    [string]$PublishDirectory,

    [Parameter(Mandatory = $true)]
    [string]$OutputPath,

    [string]$OwnedFilesPath
)

$ErrorActionPreference = 'Stop'
$publishRoot = [System.IO.Path]::GetFullPath($PublishDirectory).TrimEnd('\', '/')
if (-not (Test-Path -LiteralPath $publishRoot -PathType Container)) {
    throw "Publish directory does not exist: $publishRoot"
}

if ([string]::IsNullOrWhiteSpace($OwnedFilesPath)) {
    $OwnedFilesPath = Join-Path $PSScriptRoot 'OwnedFiles.txt'
}

$ownedFilesFullPath = [System.IO.Path]::GetFullPath($OwnedFilesPath)
if (-not (Test-Path -LiteralPath $ownedFilesFullPath -PathType Leaf)) {
    throw "Owned-file ledger does not exist: $ownedFilesFullPath"
}

function ConvertTo-NsisLiteral([string]$Value) {
    return $Value.Replace('$', '$$').Replace('"', '$\"')
}

function Normalize-OwnedRelativePath([string]$Value) {
    $normalized = $Value.Trim().Replace('/', '\')
    if ([string]::IsNullOrWhiteSpace($normalized) -or
        [System.IO.Path]::IsPathRooted($normalized) -or
        $normalized.StartsWith('\') -or
        $normalized.IndexOfAny([char[]]'*?') -ge 0 -or
        $normalized.Split('\', [System.StringSplitOptions]::RemoveEmptyEntries) -contains '..') {
        throw "Unsafe path in owned-file ledger: $Value"
    }

    return $normalized
}

$ownedFiles = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
foreach ($line in Get-Content -LiteralPath $ownedFilesFullPath) {
    $trimmed = $line.Trim()
    if ([string]::IsNullOrWhiteSpace($trimmed) -or $trimmed.StartsWith('#')) {
        continue
    }

    $relativePath = Normalize-OwnedRelativePath $trimmed
    if (-not $ownedFiles.Add($relativePath)) {
        throw "Duplicate path in owned-file ledger: $relativePath"
    }
}

$currentFiles = @(
    Get-ChildItem -LiteralPath $publishRoot -File -Recurse |
        ForEach-Object {
            $_.FullName.Substring($publishRoot.Length).TrimStart('\', '/').Replace('/', '\')
        }
)

$currentFileSet = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
foreach ($relativePath in $currentFiles) {
    [void]$currentFileSet.Add($relativePath)
}

foreach ($relativePath in $currentFiles) {
    if (-not $ownedFiles.Contains($relativePath)) {
        throw "Publish file is missing from installer/OwnedFiles.txt: $relativePath"
    }
}

$directories = [System.Collections.Generic.HashSet[string]]::new([System.StringComparer]::OrdinalIgnoreCase)
foreach ($relativePath in $ownedFiles) {
    $directory = Split-Path -Parent $relativePath
    while (-not [string]::IsNullOrWhiteSpace($directory)) {
        [void]$directories.Add($directory)
        $directory = Split-Path -Parent $directory
    }
}

$lines = [System.Collections.Generic.List[string]]::new()
$lines.Add('; Generated by Generate-UninstallManifest.ps1. Do not edit or commit.')
$lines.Add('; Cumulative application-owned paths only; preserve every unknown user file.')
$lines.Add('!macro DeleteTabletMidiPadStaleFiles')

foreach ($relativePath in $ownedFiles | Where-Object { -not $currentFileSet.Contains($_) } | Sort-Object) {
    $literal = ConvertTo-NsisLiteral $relativePath
    $lines.Add("  Delete `"`$INSTDIR\$literal`"")
}

$lines.Add('!macroend')
$lines.Add('!macro DeleteTabletMidiPadOwnedFiles')

foreach ($relativePath in $ownedFiles | Sort-Object) {
    $literal = ConvertTo-NsisLiteral $relativePath
    $lines.Add("  Delete `"`$INSTDIR\$literal`"")
}

$lines.Add('!macroend')
$lines.Add('!macro RemoveTabletMidiPadOwnedDirectories')

foreach ($relativeDirectory in $directories | Sort-Object @{ Expression = { $_.Length }; Descending = $true }, @{ Expression = { $_ }; Descending = $false }) {
    $literal = ConvertTo-NsisLiteral $relativeDirectory
    $lines.Add("  RMDir `"`$INSTDIR\$literal`"")
}

$lines.Add('!macroend')

$outputFullPath = [System.IO.Path]::GetFullPath($OutputPath)
$outputDirectory = Split-Path -Parent $outputFullPath
if (-not [string]::IsNullOrWhiteSpace($outputDirectory)) {
    New-Item -ItemType Directory -Path $outputDirectory -Force | Out-Null
}

[System.IO.File]::WriteAllLines($outputFullPath, $lines, [System.Text.UTF8Encoding]::new($false))
Write-Output "Generated cumulative uninstall manifest for $($ownedFiles.Count) owned file(s): $outputFullPath"
